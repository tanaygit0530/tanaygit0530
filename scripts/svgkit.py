def icon(name, x, y, size=26, color=ACCENT, width=1.8):
    s = size / 24
    paths = "".join(f'<path d="{d}"/>' for d in ICONS[name])
    return (f'<g transform="translate({x} {y}) scale({s})" fill="none" stroke="{color}" '
            f'stroke-width="{width / s:.2f}" stroke-linecap="round" stroke-linejoin="round">{paths}</g>')


def github_logo(x, y, size, color=TEXT):
    s = size / 24
    return f'<path transform="translate({x} {y}) scale({s})" fill="{color}" d="{GITHUB_PATH}"/>'


def text(x, y, s, size=20, color=TEXT, weight=400, anchor="start", extra=""):
    return (f'<text x="{x}" y="{y}" font-family="{FONT}" font-size="{size}" font-weight="{weight}" '
            f'fill="{color}" text-anchor="{anchor}" {extra}>{escape(s)}</text>')


def svg(width, height, body, title, bg=True):
    back = f'<rect width="{width}" height="{height}" fill="{BG}"/>' if bg else ""
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
            f'viewBox="0 0 {width} {height}" role="img" aria-label="{escape(title)}">'
            f'<title>{escape(title)}</title>{back}{body}</svg>\n')
